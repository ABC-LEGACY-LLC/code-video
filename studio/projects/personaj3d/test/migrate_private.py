JSTR = re.compile(r'"(?:[^"\\]|\\.)*"')


def json_words(text):
    """translate JSON string tokens (keys and values) that are in WORDS; everything else, numbers included, stays as written"""
    def f(m):
        raw = m.group(0)
        try:
            v = json.loads(raw)
        except ValueError:
            return raw
        nv = WORDS.get(v)
        return json.dumps(nv, ensure_ascii=False) if nv is not None else raw
    return JSTR.sub(f, text)


def main():
    if len(sys.argv) < 2:
        print(__doc__); sys.exit(2)
    old = os.path.abspath(sys.argv[1])
    new = os.path.abspath(sys.argv[2]) if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'private')
    if os.path.isdir(new) and os.listdir(new):
        print('the target folder is not empty:', new); sys.exit(1)
    unknown = []
    n = 0
    for dp, dn, fn in os.walk(old):
        for f in sorted(fn):
            rel = os.path.relpath(os.path.join(dp, f), old)
            to = FILES.get(rel)
            if to is None:
                unknown.append(rel); to = rel
            dst = os.path.join(new, to)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            if rel.endswith('.json') and not rel.startswith('sam2/'):
                with open(os.path.join(old, rel), encoding='utf-8') as fi:
                    text = fi.read()
                with open(dst, 'w', encoding='utf-8') as fo:
                    fo.write(json_words(text))
            else:
                shutil.copy2(os.path.join(old, rel), dst)
            n += 1
    print(n, 'files ->', new)
    if unknown:
        print('not in the table, copied under the old name (%d):' % len(unknown))
        for u in unknown:
            print('  ', u)


if __name__ == '__main__':
    main()
